#!/bin/sh
# Generate the module-to-test ledger from tracked Salam sources.

set -eu
LC_ALL=C
export LC_ALL

ROOT=$(CDPATH= cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

tmp="${TMPDIR:-/tmp}/mizrab-coverage.$$"
mkdir "$tmp"
trap 'rm -rf "$tmp"' 0
trap 'exit 1' HUP INT TERM

git ls-files '*.salam' | sort >"$tmp/sources"
: >"$tmp/rows"
covered=0
untested=0

while IFS= read -r source; do
    case "$source" in
        tests/*) continue ;;
    esac

    case "$source" in
        */*)
            dir=${source%/*}
            package="$dir/${dir##*/}.salam"
            ;;
        *)
            dir=
            package=
            ;;
    esac

    matches=
    for test_file in tests/*_test.salam; do
        [ -f "$test_file" ] || continue
        matched=0

        if grep -Fq "include \"../$source\"" "$test_file"; then
            matched=1
        elif [ -n "$package" ] && [ -f "$package" ]; then
            if [ "$source" != "$package" ] && grep -Fq "include \"../$package\"" "$test_file"; then
                matched=1
            elif [ "$source" = "$package" ]; then
                for leaf in "$dir"/*.salam; do
                    [ -f "$leaf" ] || continue
                    [ "$leaf" = "$source" ] && continue
                    if grep -Fq "include \"../$leaf\"" "$test_file"; then
                        matched=1
                        break
                    fi
                done
            fi
        fi

        if [ "$matched" -eq 1 ]; then
            name=${test_file##*/}
            name=${name%.salam}
            if [ -n "$matches" ]; then
                matches="$matches,$name"
            else
                matches=$name
            fi
        fi
    done

    if [ -n "$matches" ]; then
        covered=$((covered + 1))
    else
        matches=-
        untested=$((untested + 1))
    fi
    printf '%s | %s\n' "$source" "$matches" >>"$tmp/rows"
done <"$tmp/sources"

printf '# generated by tests/coverage.sh; do not edit\n'
cat "$tmp/rows"
printf '# covered: %s, untested: %s\n' "$covered" "$untested"
